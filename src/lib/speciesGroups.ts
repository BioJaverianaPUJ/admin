const byFamily = new Map<string, SpeciesGroup>();
for (const [key, list] of Object.entries(families) as [Key, string[]][])
  for (const f of list) byFamily.set(f, groups[key]);

const letters = "a-záéíóúñü";
const byKeyword = (Object.entries(keywords) as [Key, string[]][]).flatMap(
  ([key, words]) =>
    words.map((w) => ({
      test: new RegExp(`(^|[^${letters}])${w}($|[^${letters}])`, "i"),
      group: groups[key],
    })),
);

export function speciesGroup(row: {
  family?: string | null;
  commonName?: string | null;
  scientificName?: string | null;
}): SpeciesGroup {
  const family = (row.family ?? "").trim().toLowerCase();
  const found = byFamily.get(family);
  if (found) return found;
  const names = [row.commonName, row.scientificName]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();
  return byKeyword.find((k) => k.test.test(names))?.group ?? groups.plant;
}
